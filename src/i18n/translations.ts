/**
 * Builds a robust Translations object with fallback to English for any missing keys
 * and dynamic todayDate calculation.
 */
function createLanguageTranslations(lang: Language): Translations {
  const specific = baseTranslations[lang] || {};
  const en = baseTranslations.en as Translations;

  return new Proxy(specific as Translations, {
    get(target, prop: keyof Translations) {
      if (prop === 'todayDate') {
        return getFormattedTodayDate(lang);
      }
      if (target[prop] !== undefined) {
        return target[prop];
      }
      return en[prop] || '';
    },
  });
}


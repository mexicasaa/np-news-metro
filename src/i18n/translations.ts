export const getFormattedTodayDate = (lang: Language = 'hi', isShort: boolean = false): string => {
  const now = new Date();
  const locale = LOCALE_MAP[lang] || 'en-US';
  try {
    return isShort
      ? new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric', year: 'numeric' }).format(now)
      : new Intl.DateTimeFormat(locale, { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric' }).format(now);
  } catch (e) {
    return isShort ? '27 Sep 2026' : 'Sunday, September 27, 2026';
  }
};

